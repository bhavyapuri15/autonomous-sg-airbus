"""Generate the evaluation case files.

Deterministic families (regenerated byte-identically): split map, F1, F7.
Hand-written families (validated, NOT regenerated): F2/F3 questions live in evaluation/sources/f2_{split}.jsonl
(written by a Claude Sonnet agent; see README). This script attaches gold offsets, the trigram overlap, and
alternates, and asserts every gold/answer span is an exact substring of doc_text.

Usage: python evaluation/generate_cases.py [--manifest]
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import split as S  # noqa: E402

CASES = S.CASES_DIR
SOURCES = S.EVAL_DIR / "sources"
MANIFEST = S.EVAL_DIR / "LOCKED_MANIFEST.sha256"
MAX_OVERLAP = 0.35


def h(*parts) -> int:
    return int(hashlib.sha256("|".join(map(str, parts)).encode()).hexdigest(), 16)


def dumps(rows) -> str:
    return "".join(json.dumps(r, sort_keys=True, ensure_ascii=False) + "\n" for r in rows)


def case(id_, family, split, prov, query, inputs, expected, gold, notes=""):
    return dict(id=id_, family=family, split=split, provenance=prov, query=query, inputs=inputs,
                expected=expected, gold_evidence=gold, notes=notes)


# ----------------------------------------------------------------------------- data
def load_db():
    con = S.connect()
    docs = {}
    for d, vol, sp, ep, dj, cls in con.execute(
            "select fr_docnum, volume, start_page, end_page, docket_ids_json, doc_class from documents where source='organiser_sheet'"):
        docs[d] = dict(volume=vol, start=sp, end=ep, dockets=S.normalize_dockets(json.loads(dj or "[]")), cls=cls)
    texts = {d: t for d, t in con.execute("select fr_docnum, text from doc_text")}
    sections = {}
    for d, path, s, e, t in con.execute("select fr_docnum, section_path, start_char, end_char, text from sections order by fr_docnum, seq"):
        sections.setdefault(d, []).append((path, s, e, t))
    rows = con.execute("select row, docket_norm, fr_docnum, subject, make_norm from records order by row").fetchall()
    ad_numbers = {r[0] for r in con.execute("select ad_number from records where ad_number<>''")}
    return docs, texts, sections, rows, ad_numbers


def all_known_ids(docs, rows, ad_numbers):
    ids = set(docs)
    for d in docs.values():
        ids |= {x.upper() for x in d["dockets"]}
    for _, dn, _, _, _ in rows:
        ids.add((dn or "").upper())
    ids |= {a.upper() for a in ad_numbers}
    return ids


def id_exists(x, known, texts) -> bool:
    xu = x.upper()
    if xu in known or any(xu == S.docket_key(k) for k in known):
        return True
    return any(x in t for t in texts.values())


# ----------------------------------------------------------------------------- F1
def f1_cases(split, docs, sm):
    out, seen = [], set()
    dk = {}
    for d, v in docs.items():
        for x in v["dockets"]:
            dk.setdefault(S.docket_key(x), set()).add(d)
    mine = sorted(d for d in docs if sm["docs"][d]["split"] == split)
    all_dockets = [x for v in docs.values() for x in v["dockets"]]

    def add(d, typ, query, expected_docs, prov="real", notes=""):
        if (query) in seen:
            return
        seen.add(query)
        out.append(case(f"F1-{d}-{typ}", "F1", split, prov, query, {},
                        {"fr_docnums": sorted(expected_docs), "match": "any", "id_type": typ},
                        [dict(fr_docnum=x, section_path=None, start_char=None, end_char=None) for x in sorted(expected_docs)], notes))

    for d in mine:
        v = docs[d]
        prim = next((x for x in v["dockets"] if x.startswith("FAA-")), v["dockets"][0] if v["dockets"] else None)
        types = ["docnum", "citation_start"]
        if prim:
            types.insert(0, "docket_exact")
        multipage = v["end"] > v["start"]
        if multipage and h("f1", d) % 2 == 0:
            types.append("citation_mid")
        elif prim:
            types.append("docket_variant")
        for t in types:
            if t == "docket_exact":
                add(d, t, prim, dk[S.docket_key(prim)])
            elif t == "docket_variant":
                opts = [prim.lower(), prim.replace("-", " ")]
                bare = re.sub(r"^FAA-", "", prim)
                if bare != prim and not any(bare.upper() in x.upper() and x.upper() != prim.upper() for x in all_dockets):
                    opts.append(bare)
                else:
                    opts.append(re.sub(r"-AD$", "", prim) if prim.endswith("-AD") else prim.replace("-", ""))
                q = opts[h("f1v", d) % len(opts)]
                if q != prim:
                    add(d, t, q, dk[S.docket_key(prim)], notes="format variant of " + prim)
            elif t == "docnum":
                add(d, t, d, {d})
            elif t in ("citation_start", "citation_mid"):
                page = v["start"] if t == "citation_start" else v["start"] + (v["end"] - v["start"] + 1) // 2
                exp = {x for x, w in docs.items() if w["volume"] == v["volume"] and w["start"] <= page <= w["end"]}
                if any(sm["docs"][x]["split"] != split for x in exp):
                    continue  # page also holds a doc from the other split: skip rather than leak / mis-score
                add(d, t, f"{v['volume']} FR {page}", exp, notes="expected = every doc whose page range contains the page")
    return out


